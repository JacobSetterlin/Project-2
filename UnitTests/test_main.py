"""
test_main.py
Used to hold unit tests for main.py using pytest.

Some lines of code were generated by Claude Sonnet 5.5, and are maked with 
comments in such places.
"""

import pytest
import unittest.mock as mock
from main import Main

def test_handle_created_input():
    planet = 'planetname'
    
    main = Main()
    main.created_planets = [planet]

    with mock.patch.object(main, "_display_custom_planet") as mock_display:
        main._handle_input(planet)

    mock_display.assert_called_once_with(planet)

def test__handle_native_input():
    main = Main()
    planet = 'earth'
    
    assert planet in main.native_planet

    with mock.patch.object(main, "_display_native_planet_info") as mock_display:
        main._handle_input(planet)

    mock_display.assert_called_once_with(planet)

def test__handle_c_input():
    main = Main()
    main.planet_creator = mock.MagicMock()

    # The below with statement was generated by Claude Sonnet 5.5
    # unittest.mock.patch is used to allow the testing of methods which 
    # interact with files, without actually interacting with those files.
    # unittest.mock.open() is used to open a file which you do not really want
    # to read or write to.
    with mock.patch("builtins.open", mock.mock_open()), \
            mock.patch("json.dump") as mock_dump, \
            mock.patch.object(main, "_gather_save_data", return_value=['newplanet']) as mock_gather:
                main._handle_input('c')
    
    main.planet_creator.create_planet.assert_called_once()
    mock_dump.assert_called_once()
    mock_gather.assert_called_once()

    assert main.created_planets == ['newplanet']

def test__handle_q_input():
    main = Main()
    with pytest.raises(SystemExit):
        main._handle_input('q')

def test__handle_unrecognized_input(capsys):
    main = Main()
    planet = 'unrecognized'

    main._handle_input(planet)

    assert capsys.readouterr().out == 'Command not recognized.\n'

def test__line_break(capsys):
    main = Main()

    main._line_break()

    assert capsys.readouterr().out == "--------------------\n"

def test__display_custom_planet(capsys):
    main = Main()
    user_input = 'input'
    main.created_planets = {user_input: 'planet_desc'}

    main._display_custom_planet(user_input)

    assert capsys.readouterr().out == f'{user_input}: \n{main.created_planets[user_input]}\n'